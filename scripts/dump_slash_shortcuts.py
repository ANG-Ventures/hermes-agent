#!/usr/bin/env -S bash -c 'exec "$BASH" "$(dirname "$0")/_hermes-python" "$0" "$@"'
"""Regenerate docs/sync/slash-shortcuts.md (every short slash alias) from COMMAND_REGISTRY.

Run after changing a short alias in ``hermes_cli/commands.py``; ``--check`` writes nothing and exits 1
when the committed doc differs (``tests/hermes_cli/test_slash_shortcuts_doc.py`` gives the same verdict).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "sync" / "slash-shortcuts.md"
MAX_LEN = 3  # "short" = what you type instead of the name
FORK_RULINGS = {"s", "st", "m", "r"}  # Ace 2026-10-18; guarded by tests/fork_canaries/test_fork_canary_short_aliases.py


def render() -> str:
    sys.path.insert(0, str(ROOT))
    from hermes_cli.commands import COMMAND_REGISTRY

    rows = sorted((alias, cmd.name) for cmd in COMMAND_REGISTRY for alias in cmd.aliases if len(alias) <= MAX_LEN)
    lines = [
        "# Slash command shortcuts (fork)",
        "",
        "Generated by `scripts/dump_slash_shortcuts.py` from `hermes_cli/commands.py`. Do not edit by hand.",
        "Registry aliases work on every surface (CLI, TUI, gateway: Discord, Telegram, Slack).",
        "Rows marked `fork` are Ace's 2026-10-18 rulings; upstream binds `/s` to `/steer` and has no `/st` `/m` `/r`.",
        "",
        "| Shortcut | Command | Origin |",
        "|---|---|---|",
    ]
    lines += [f"| `/{a}` | `/{n}` | {'fork' if a in FORK_RULINGS else 'upstream'} |" for a, n in rows]
    return "\n".join(lines) + "\n"


def check(out: Path = OUT) -> int:
    committed = out.read_text(encoding="utf-8") if out.exists() else ""
    if committed == render():
        return 0
    print(f"{out.relative_to(ROOT)} is stale — run scripts/dump_slash_shortcuts.py", file=sys.stderr)
    return 1


def main(argv: list[str]) -> int:
    if argv == ["--check"]:
        return check()
    if argv:
        print(f"usage: {Path(__file__).name} [--check]", file=sys.stderr)
        return 2
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
